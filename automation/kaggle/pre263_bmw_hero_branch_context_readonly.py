#!/usr/bin/env python3
"""PRE263: inspect exact PAL/USA BMW hero UI candidate functions and callers.
No code changes, saves, keys, or Android builds. Function identity is a
candidate until tied to actual V37 runtime call path.
"""
from __future__ import annotations
import argparse, hashlib, json, re, sys, tarfile, tempfile
from datetime import datetime,timezone
from pathlib import Path
from pre104_verify_backup_tar import EXPECTED_BYTES,EXPECTED_SHA256,sha_file
from pre105_read_settings_source import drive_client,download

OUT=Path("/tmp/nfsmw-pre263/PRE263_BMW_HERO_BRANCH_CONTEXT_READONLY.json")
ROOTS={"PAL":"workspace/nativo/app/generated/default/",
       "USA":"workspace/nativo/app_usa/generated/default/"}
TARGET={
 "PAL":["sub_8256FD30","sub_82578670","sub_82578988","sub_82582F70",
        "sub_82576AB8","sub_82577C88","sub_8257E288","sub_822CC740"],
 "USA":["sub_8256FB38","sub_82578478","sub_82578790","sub_82582D78"]
}
DEF=re.compile(r"(?m)^DEFINE_REX_FUNC\((sub_[0-9a-fA-F]{8})\)")
CALL=re.compile(r"__imp__(sub_[0-9a-fA-F]{8})\s*\(ctx,\s*base\)")
HERO_CMP=re.compile(r"(?i)^\s*//\s*cmpwi\s+cr\d+,r3,41\s*$",re.M)
OUTPUT_CHARS_PER_FUNCTION=41000
MAX_CPP_FILE=7_000_000

def audit(tmp):
    arch=tmp/"pre99.tar.gz"
    download(drive_client(),arch)
    digest,_,size=sha_file(arch)
    if digest!=EXPECTED_SHA256 or size!=EXPECTED_BYTES:raise ValueError("PRE99 mismatch")
    output={"stage":"PRE263_BMW_HERO_UI_BRANCH_CONTEXT",
       "status":"AUDIT_OK","archive_verified_sha256":digest,"read_only":True,
       "apk_built":False,"patched":False,"save_touched":False,"signer_access":False,
       "mapped_to_v37":False,"selected_functions":[],"caller_sites":[],
       "source_cpp_files":{},"known_decomp_model_enum":41,
       "target_list":TARGET}
    counts={"PAL":0,"USA":0}
    xref_targets=set(TARGET["PAL"]+TARGET["USA"])
    with tarfile.open(arch,"r:gz",errorlevel=2) as tar:
      for m in tar:
        if not m.isfile() or not m.name.endswith(".cpp"):continue
        name=m.name.lstrip("./")
        ed=next((k for k,p in ROOTS.items() if name.startswith(p)),None)
        if ed is None:continue
        if m.size>MAX_CPP_FILE:raise ValueError("Unexpected generated file size")
        f=tar.extractfile(m)
        if f is None:raise ValueError("Missing generated bytes")
        raw=f.read()
        if len(raw)!=m.size:raise ValueError("Truncated source")
        counts[ed]+=1
        src=raw.decode("utf-8","replace")
        defs=list(DEF.finditer(src))
        if not defs:continue
        for i,d in enumerate(defs):
          fname=d.group(1)
          start=d.start()
          end=defs[i+1].start() if i+1<len(defs) else len(src)
          # Avoid slicing bodies from irrelevant functions.
          relevant=fname in TARGET[ed]
          body=src[start:end] if relevant else None
          if relevant:
            instructions=body.splitlines()
            comparisons=[{"relative_line":j+1,"text":line.strip()}
                         for j,line in enumerate(instructions)
                         if re.search(r"\b(?:cmpwi|cmplwi)\b.*(?:,41|,0x29)\b",line,re.I)]
            calls=[c.group(1) for c in CALL.finditer(body)]
            output["selected_functions"].append({
              "edition":ed,"name":fname,"file":name,
              "file_sha256":hashlib.sha256(raw).hexdigest(),
              "body_chars":len(body),"body_truncated":len(body)>OUTPUT_CHARS_PER_FUNCTION,
              "body_excerpt":body[:OUTPUT_CHARS_PER_FUNCTION],
              "comparisons":comparisons[:18],"calls":calls[:150],
              "model_compare_lines":len(comparisons)
            })
          # Keep xrefs to the identified IsHeroCar method and its potential
          # GetType callee. This scans each function only after file text has
          # been validated against the pinned archive.
          if not relevant and (ed=="PAL"):
            target_calls=[]
            # Some candidates are called by wrapper; capture capped samples.
            for target in ("sub_8256FD30","sub_822CC740"):
              if ("__imp__"+target+"(") not in src[start:end]:continue
              target_calls.append(target)
            if target_calls and len(output["caller_sites"])<120:
              output["caller_sites"].append({
                 "edition":ed,"caller":fname,"file":name,
                 "targets":target_calls,
                 "caller_chars":end-start,
                 "contains_cmp_41":bool(HERO_CMP.search(src[start:end])),
                 "first_lines":src[start:min(end,start+400)].splitlines()[:18]
              })
        if any(f["file"]==name for f in output["selected_functions"]):
          output["source_cpp_files"][name]=hashlib.sha256(raw).hexdigest()
    output["generated_cpp_file_count"]=counts
    output["selected_function_count"]=len(output["selected_functions"])
    for ed, names in TARGET.items():
      absent=[x for x in names if not any(z["edition"]==ed and z["name"]==x for z in output["selected_functions"])]
      if absent:
        output["status"]="NEEDS_REVIEW"
        output.setdefault("missing_targets",{})[ed]=absent
    output["limitations"]=[
      "Identical compare to BMW model enum does not identify every caller's high-level method",
      "Decompilation version equivalence with the PAL V37 binary is not proven",
      "No conditional menu patch has been applied",
      "A menu patch alone does not prove GetMaxLevel supports this car",
      "Only read authenticated PRE99 and generated synthetic JSON"
    ]
    return output

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--run-id",required=True)
    a=p.parse_args()
    if not a.run_id.isdecimal():raise ValueError("run-id invalid")
    OUT.parent.mkdir(parents=True,exist_ok=True)
    result={"status":"FAILED","stage":"PRE263_BMW_HERO_UI_BRANCH_CONTEXT",
            "read_only":True,"apk_built":False,"patched":False}
    try:
      with tempfile.TemporaryDirectory(prefix="pre263_") as tmp:
        result=audit(Path(tmp))
    except Exception as e:
      result["error_type"]=type(e).__name__
    result["run_id"]=a.run_id
    result["time_utc"]=datetime.now(timezone.utc).isoformat()
    OUT.write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n",encoding="utf8")
    print("PRE263_STATUS",result["status"])
    print("PRE263_FOUND",result.get("selected_function_count"))
    print("PRE263_PAL_CPP",result.get("generated_cpp_file_count",{}).get("PAL"))
    if result["status"]!="AUDIT_OK":print("PRE263_ERROR",result.get("error_type"),result.get("missing_targets"))
    return 0 if result["status"]=="AUDIT_OK" else 1
if __name__=="__main__":sys.exit(main())
